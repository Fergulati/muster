#!/usr/bin/env python3
"""Generate ui/tests/gallery/FakeBackend.qml from the view contract, ui/src/muster_ui.rep.

The gallery (scripts/ui-screenshot.sh, exo-720.2) renders the real QML against this fake
instead of the QtRO replica: every PROP becomes a string property holding its contract
default, every SLOT a function that records the call and does nothing else. A fixture then
sets the PROPs it needs. Generated, never hand-edited, so it cannot drift from the .rep:
`--check` exits 1 when the committed file is stale.

    python3 ui/tools/gen-fake-backend.py          # write
    python3 ui/tools/gen-fake-backend.py --check  # verify
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
REP = ROOT / "ui/src/muster_ui.rep"
OUT = ROOT / "ui/tests/gallery/FakeBackend.qml"

PROP = re.compile(r'^\s*PROP\(\s*QString\s+(\w+)\s*=\s*"((?:[^"\\]|\\.)*)"', re.M)
SLOT = re.compile(r'^\s*SLOT\(\s*[\w:<>]+\s+(\w+)\s*\(([^)]*)\)', re.M)


def cpp_unescape(s: str) -> str:
    return s.encode().decode("unicode_escape")


def arg_names(sig: str) -> list[str]:
    names = []
    for part in [p.strip() for p in sig.split(",") if p.strip()]:
        names.append(re.findall(r"(\w+)\s*$", part)[0])
    return names


def render() -> str:
    rep = REP.read_text()
    props = PROP.findall(rep)
    slots = SLOT.findall(rep)
    # every PROP in the contract is a QString today; a new type needs a mapping here
    declared = re.findall(r'^\s*PROP\(\s*(\w+)\s+(\w+)', rep, re.M)
    odd = [n for t, n in declared if t != "QString"]
    if odd or len(declared) != len(props):
        sys.exit(f"gen-fake-backend: PROPs this generator can't map: {odd or 'a default it cannot parse'}")
    lines = [
        "// GENERATED by ui/tools/gen-fake-backend.py from ui/src/muster_ui.rep — do not edit.",
        "// The gallery's stand-in for the muster_ui replica (exo-720.2): the contract's PROPs at",
        "// their defaults, its SLOTs as recorders. A fixture sets the PROPs it needs.",
        "import QtQuick",
        "",
        "QtObject {",
        "    // the contract's PROP names, in .rep order (the recorder snapshots exactly these)",
        f"    readonly property var contractProps: {json.dumps([n for n, _ in props])}",
        "    // every SLOT call, in order: [{slot, args}]",
        "    property var calls: []",
        "    function record(slot, args) { calls.push({ slot: slot, args: Array.prototype.slice.call(args) }); }",
        "",
    ]
    for name, default in props:
        lines.append(f"    property string {name}: {json.dumps(cpp_unescape(default))}")
    lines.append("")
    for name, sig in slots:
        args = ", ".join(arg_names(sig))
        lines.append(f"    function {name}({args}) {{ record({json.dumps(name)}, arguments); }}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 ui/tools/gen-fake-backend.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
