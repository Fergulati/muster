#!/usr/bin/env bash
# Build the Nim UI's runner (exo-607 T6, ADR-019): .run/runner-nim/bin/muster-ui, which
# the offscreen self-tests drive with MUSTER_UI=nim (scripts/lib/ui-build.sh). It runs
# ui-nim#muster-app, the standalone seaqt app, against the modules the C++ runner was
# built with, so the two builds differ only in their UI and their in-process Logos
# libraries (the app's own Qt 6.11; the modules keep Logos's 6.9.2).
#
# It needs a C++ runner (make build) for those modules, and builds nothing that make
# build would: the app's flake (ui-nim) is small and separate. MUSTER_RUNNER names
# another runner to take the modules from.
set -euo pipefail
cd "$(dirname "$0")/.."
CPP="${MUSTER_RUNNER:-.run/runner}/bin/muster-ui"
[ -x "$CPP" ] || { echo "build the C++ runner first (make build): its modules are what the Nim runner loads" >&2; exit 1; }
LAUNCH=$(grep -oE '/nix/store/[^ "]+/bin/run-logos-standalone-ui' "$CPP" | head -1)
MODULES=$(grep -oE -- '--modules-dir "[^"]+"' "$LAUNCH" | cut -d'"' -f2)
[ -d "$MODULES" ] || { echo "could not find the C++ runner's modules dir (from $LAUNCH)" >&2; exit 1; }

# The app, GC-rooted under .run/ like the C++ runner.
(cd ui-nim && nix build .#muster-app --accept-flake-config --out-link ../.run/muster-app)
APP=$(readlink -f .run/muster-app)

mkdir -p .run/runner-nim/bin
cat > .run/runner-nim/bin/muster-ui <<EOF
#!/usr/bin/env bash
# Generated by scripts/build-runner-nim.sh: the Nim UI (ui-nim#muster-app) on the
# C++ runner's modules. Takes what logos-standalone-app takes (--user-dir or
# LOGOS_USER_DIR, LOGOS_INSTANCE_ID, the MUSTER_* environment).
exec "$APP/bin/muster-app" --modules "$MODULES" "\$@"
EOF
chmod +x .run/runner-nim/bin/muster-ui
echo "runner-nim: .run/runner-nim/bin/muster-ui"
echo "  app:     $APP"
echo "  modules: $MODULES"
