#!/usr/bin/env python3
"""The site's /support/ page, from the file every build pins (exo-168).

Muster's "Like Muster?" modal shows the tip addresses in module/src/wallet/support.json,
read into the module at build time. This page publishes the same file, so anyone can check
the addresses a copy of Muster shows against the repo before sending anything. One source:
a pull request that changes an address changes both, in the open.

  scripts/gen-support-page.py OUT.html     # scripts/build-site.sh runs it
"""

from __future__ import annotations

import html
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "module" / "src" / "wallet" / "support.json"

# the landing page's tokens (site/index.html), light and dark
STYLE = """
:root{
  --paper:#E4E6E0; --surface:#F7F8F5; --raised:#FFFFFF; --ink:#1A1F1C; --ink-2:#3F4742; --muted:#656E66; --rule:#C6CBC3;
  --signal:#4B33C4; --signal-soft:#EAE6FA;
  --ui:"Instrument Sans",-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif;
  --mono:"DM Mono",ui-monospace,"SF Mono",Menlo,monospace;
  --r:10px;
}
@media (prefers-color-scheme: dark){
  :root:not([data-theme="light"]){
    color-scheme:dark;
    --paper:#111412; --surface:#181C19; --raised:#1E2320; --ink:#E3E7E2; --ink-2:#B6BEB8; --muted:#8E978F; --rule:#2F3631;
    --signal:#A99AF7; --signal-soft:#26213F;
  }
}
:root[data-theme="dark"]{
  color-scheme:dark;
  --paper:#111412; --surface:#181C19; --raised:#1E2320; --ink:#E3E7E2; --ink-2:#B6BEB8; --muted:#8E978F; --rule:#2F3631;
  --signal:#A99AF7; --signal-soft:#26213F;
}
*{box-sizing:border-box}
html,body{margin:0}
body{background:var(--paper);color:var(--ink);font-family:var(--ui);font-size:16px;line-height:1.6;-webkit-font-smoothing:antialiased}
a{color:var(--signal);text-underline-offset:.18em}
main{max-width:760px;margin:0 auto;padding:40px 16px 64px}
h1{font-size:32px;margin:0 0 8px}
h2{font-size:13px;font-family:var(--mono);letter-spacing:.12em;text-transform:uppercase;color:var(--muted);margin:36px 0 12px}
p{margin:0 0 12px;color:var(--ink-2)}
.row{background:var(--surface);border:1px solid var(--rule);border-radius:var(--r);padding:16px;margin:0 0 12px}
.row h3{margin:0 0 4px;font-size:17px}
.row .for{margin:0 0 10px;font-size:14px}
.addr{font-family:var(--mono);font-size:13px;word-break:break-all;background:var(--raised);border:1px solid var(--rule);border-radius:6px;padding:8px 10px;margin:0}
.meta{font-family:var(--mono);font-size:12px;color:var(--muted);margin:8px 0 0}
.empty{font-style:italic;color:var(--muted)}
"""


def row(a: dict) -> str:
    addr = a.get("address", "").strip()
    body = (f'<p class="addr">{html.escape(addr)}</p>' if addr
            else '<p class="empty">Not set yet.</p>')
    return (f'<section class="row" id="{html.escape(a["id"])}">'
            f'<h3>{html.escape(a["name"])}</h3>'
            f'<p class="for">{html.escape(a.get("for", ""))}</p>'
            f'{body}'
            f'<p class="meta">{html.escape(a["chain"])}</p>'
            f'</section>')


def page(data: dict) -> str:
    rows = data["addresses"]
    mains = "".join(row(a) for a in rows if not a.get("testnet"))
    tests = "".join(row(a) for a in rows if a.get("testnet"))
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Support Muster</title>
<meta name="description" content="The addresses Muster's Like Muster? tip button pays, published from the same file the app is built with.">
<meta name="color-scheme" content="light dark">
<!-- GENERATED by scripts/gen-support-page.py from module/src/wallet/support.json — do not edit. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Instrument+Sans:wght@400;600;700&family=DM+Mono:wght@400;500&display=swap" rel="stylesheet">
<style>{STYLE}</style>
</head>
<body>
<main>
<p><a href="../">← Muster</a></p>
<h1>Like Muster?</h1>
<p>{html.escape(data.get("about", ""))}</p>
<p>These are the addresses the app's <b>Like Muster?</b> button pays. Each copy of Muster
carries them from <a href="https://github.com/corpetty/muster/blob/main/module/src/wallet/support.json">one
file in the repository</a>, and this page is built from that same file. If the app shows
an address that is not on this page, don't send to it.</p>
<h2>Tip</h2>
{mains}
<h2>Testnet coins, for the live test runs</h2>
<p>Muster is tested on live testnets, and some of those runs need coins nobody hands out:
stagenet XMR, native LEZ. A testnet coin sent here goes straight into those runs.</p>
{tests}
</main>
</body>
</html>
"""


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[-1].strip(), file=sys.stderr)
        return 2
    out = Path(argv[1])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page(json.loads(SOURCE.read_text())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
